#!/bin/sh
# Install every licence and third-party notice for the Mathlib build into one
# directory. ONE script, run by both packages that ship this code (`mathlib`
# and `mathlib-oleans`; each lists it and the notice files through
# notices.ncl), so the two cannot ship different notices.
#
#   sh install-licences.sh <locals-dir> <licence-dir> <lake-name>=<source-dir>...
#
# <locals-dir> holds the notice files from notices.ncl. One <lake-name>=<dir>
# per pinned source, named like the Lake package (mathlib, plausible,
# LeanSearchClient, importGraph, proofwidgets, aesop, Qq, batteries, Cli);
# all nine are required.
#
# Apache-2.0 s4(a)/(d): a copy of the licence and any NOTICE file; MIT: the
# copyright and permission notice. One directory per source. None of the nine
# pinned sources ships a NOTICE file; one that appears is copied too.
set -eu

LOCALS="$1"
LIC="$2"
shift 2
NAMES="mathlib plausible LeanSearchClient importGraph proofwidgets aesop Qq batteries Cli"

install_lic() { # name srcdir
  mkdir -p "$LIC/$1"
  cp "$2/LICENSE" "$LIC/$1/LICENSE"
  # `if`, not `[ … ] && cp`: with no NOTICE the && form returns 1 and
  # `set -e` would abort the build.
  for n in "$2"/NOTICE*; do
    if [ -f "$n" ]; then cp "$n" "$LIC/$1/"; fi
  done
}
PW=
for arg in "$@"; do
  name="${arg%%=*}"
  dir="${arg#*=}"
  case " $NAMES " in
    *" $name "*) ;;
    *) echo "install-licences: unknown source '$name' (expected one of: $NAMES)." >&2; exit 1 ;;
  esac
  install_lic "$name" "$dir"
  if [ "$name" = proofwidgets ]; then PW="$dir"; fi
done
if [ -z "$PW" ]; then
  echo "install-licences: no proofwidgets=<dir> argument; its widget bundles are what the notices cover." >&2
  exit 1
fi

# ProofWidgets' committed widget JS bundles npm code whose notices the
# minified files do not carry. Ship (a) the package/licence inventory and
# (b) the full third-party NOTICE (verbatim licence texts from the exact npm
# tarballs), and only if each was generated from THIS lockfile.
have_lock="$(sha256sum "$PW/widget/package-lock.json" | cut -d' ' -f1)"
install_pw_doc() { # local-file dest-name mode-flag
  want_lock="$(sed -n 's/^package-lock.json sha256: //p' "$LOCALS/$1")"
  if [ -z "$want_lock" ] || [ "$want_lock" != "$have_lock" ]; then
    echo "install-licences: $1 was generated from package-lock.json '$want_lock'," >&2
    echo "  but the pinned ProofWidgets has $have_lock. Regenerate it on a maintainer host" >&2
    echo "  from packages/mathlib (see the script's docstring):" >&2
    echo "    python3 -I gen-proofwidgets-notice.py $3<ProofWidgets4 checkout>/widget/package-lock.json \\" >&2
    echo "        <ProofWidgets commit sha> <download dir> > $1" >&2
    exit 1
  fi
  cp "$LOCALS/$1" "$LIC/proofwidgets/$2"
}
install_pw_doc proofwidgets-js-third-party.txt THIRD-PARTY-JS.txt "--inventory "
install_pw_doc proofwidgets-js-NOTICE.txt THIRD-PARTY-NOTICES.txt ""

# Two of those bundles also embed a WebAssembly build of Graphviz (EPL-2.0,
# CPL-1.0 vpsc) plus expat and the Emscripten runtime (musl, libc++,
# libc++abi, libunwind, compiler-rt), compiled into @hpcc-js/wasm's
# `wasmBinary`, and the JavaScript that decodes it (fzstd, and the basE91
# loader @hpcc-js/esbuild-plugins emits), which hpcc's build inlines. The
# npm-derived NOTICE sees none of these, so proofwidgets-wasm-NOTICE.txt
# carries those licences and the EPL/CPL source offer. It was checked
# against these exact bundles; refuse to package if either changed.
#
# penroseCanvas.js and penroseDisplay.js embed @penrose/optimizer's Rust
# WebAssembly; proofwidgets-penrose-wasm-NOTICE.txt (generated by
# gen-proofwidgets-wasm-notice.py, which fails if any crate compiled into it
# lacks a licence text) carries every crate's notice. Same hash pin.
pin_wasm_notice() { # notice-file how-to-recheck bundle...
  notice="$1"; how="$2"; shift 2
  for js in "$@"; do
    want="$(sed -n "s/^$js sha256: //p" "$LOCALS/$notice")"
    have="$(sha256sum "$PW/widget/js/$js" | cut -d' ' -f1)"
    if [ -z "$want" ] || [ "$want" != "$have" ]; then
      echo "install-licences: $notice was checked against $js '$want'," >&2
      echo "  but the pinned ProofWidgets has $have. $how" >&2
      exit 1
    fi
  done
}
pin_wasm_notice proofwidgets-wasm-NOTICE.txt \
  "It is hand-assembled: re-derive the Graphviz, expat and Emscripten (and its runtime libraries) versions from the @hpcc-js/wasm release the new lockfile pins (its vcpkg-overlays/ and scripts/cpp-install-emsdk.sh), and the inlined JS decoders from that release's dist/graphviz.js.map sources and package-lock.json (fzstd, @hpcc-js/esbuild-plugins); update the licence texts, source offer and mirror copies, then the two sha256 lines." \
  graphvizDisplay.js index.js
pin_wasm_notice proofwidgets-penrose-wasm-NOTICE.txt \
  "Regenerate it from packages/mathlib with gen-proofwidgets-wasm-notice.py (usage in its docstring) > proofwidgets-penrose-wasm-NOTICE.txt." \
  penroseCanvas.js penroseDisplay.js
# Every bundle pin in either WASM notice, not only the four named above,
# must match the installed bundle: a pin added for a new bundle is checked
# too, and a pin for a bundle that no longer exists fails.
for notice in proofwidgets-wasm-NOTICE.txt proofwidgets-penrose-wasm-NOTICE.txt; do
  sed -n 's/^\([^ /]*\.js\) sha256: \([0-9a-f]*\)$/\1 \2/p' "$LOCALS/$notice" |
    while read -r js want; do
      if [ ! -f "$PW/widget/js/$js" ]; then
        echo "install-licences: $notice pins widget/js/$js, which the pinned ProofWidgets does not have." >&2
        echo "  Re-check the notice against the bundles that exist, then drop or fix the '$js sha256:' line." >&2
        exit 1
      fi
      have="$(sha256sum "$PW/widget/js/$js" | cut -d' ' -f1)"
      if [ "$want" != "$have" ]; then
        echo "install-licences: $notice was checked against $js '$want'," >&2
        echo "  but the pinned ProofWidgets has $have. Re-check what that bundle compiles in, update the notice, then its sha256 line." >&2
        exit 1
      fi
    done
done
# Fail closed on WebAssembly no notice covers: every bundle that embeds a
# wasm module (base64 `\0asm` header, an Emscripten `wasmBinary`, or any
# WebAssembly use) must be pinned by one of the two notices above (and the
# loop above checked that pin's hash).
for f in "$PW"/widget/js/*.js; do
  js="$(basename "$f")"
  if grep -qE 'AGFzbQ|wasmBinary|WebAssembly' "$f" &&
     ! grep -q "^$js sha256: " "$LOCALS/proofwidgets-wasm-NOTICE.txt" "$LOCALS/proofwidgets-penrose-wasm-NOTICE.txt"; then
    echo "install-licences: widget/js/$js embeds WebAssembly that no WASM notice covers; refusing to package." >&2
    echo "  Find what it compiles in and add its notices (and a '$js sha256:' pin) to one of the two WASM notices." >&2
    exit 1
  fi
done
cp "$LOCALS/proofwidgets-wasm-NOTICE.txt" "$LIC/proofwidgets/THIRD-PARTY-WASM-NOTICES.txt"
cp "$LOCALS/proofwidgets-penrose-wasm-NOTICE.txt" "$LIC/proofwidgets/THIRD-PARTY-WASM-PENROSE-NOTICES.txt"

# Fail closed: every expected licence file is installed and non-empty, and
# each says what build.ncl's license_spdx claims (Apache-2.0, except
# lean4-cli's MIT).
for n in $NAMES; do
  f="$LIC/$n/LICENSE"
  if [ ! -s "$f" ]; then
    echo "install-licences: licence file $f missing or empty (was $n=<dir> passed?); refusing to package." >&2
    exit 1
  fi
  case "$n" in
    Cli) grep -q '^MIT License' "$f" ;;
    *)   grep -q 'Apache License' "$f" && grep -q 'Version 2.0, January 2004' "$f" ;;
  esac || {
    echo "install-licences: $f is not the licence build.ncl declares for $n." >&2
    echo "  Read the new LICENSE, then update license_spdx in packages/mathlib/build.ncl and" >&2
    echo "  packages/mathlib-oleans/build.ncl and the expected text in this check." >&2
    exit 1
  }
done
test -s "$LIC/proofwidgets/THIRD-PARTY-JS.txt"
test -s "$LIC/proofwidgets/THIRD-PARTY-NOTICES.txt"
test -s "$LIC/proofwidgets/THIRD-PARTY-WASM-NOTICES.txt"
test -s "$LIC/proofwidgets/THIRD-PARTY-WASM-PENROSE-NOTICES.txt"
